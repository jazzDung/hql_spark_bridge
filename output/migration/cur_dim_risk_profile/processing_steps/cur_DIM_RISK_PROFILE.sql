WITH RISK_PROFILE_ROW_NUM AS (
  SELECT
    *,
    ROW_NUMBER() OVER (PARTITION BY SOURCE_NAME, CUSTOMER_ID ORDER BY SOURCE_UPDATE_DATE DESC) AS RN
  FROM ${cur_schema}.TEMP_DIM_RISK_PROFILE
)
INSERT INTO ${cur_schema}.DIM_RISK_PROFILE PARTITION(etl_dt = '${batch_date}') (
  CUSTOMER_ID, /* None */
  AMLA_RISK_PROFILE_DATE, /* None */
  AMLATF_RISK, /* None */
  ESTIMATED_NETWORTH, /* None */
  ANNUAL_INCOME, /* None */
  SOURCE_NAME, /* None */
  SOURCE_RECORD_ID, /* None */
  ETL_TIMESTAMP,
  SOURCE_UPDATE_DATE /* 20251028 */
)
SELECT
  CUSTOMER_ID,
  AMLA_RISK_PROFILE_DATE,
  AMLATF_RISK,
  ESTIMATED_NETWORTH,
  ANNUAL_INCOME,
  SOURCE_NAME,
  SOURCE_RECORD_ID,
  ETL_TIMESTAMP,
  SOURCE_UPDATE_DATE
FROM RISK_PROFILE_ROW_NUM
WHERE
  RN = 1;