      AND TRIM(FIELDID) = 'BUSINESSTYPE'
      AND RECSTATUS = 'AA'
      AND START_DT <= '${batch_date}'
      AND END_DT > '${batch_date}'
  ) AS C
    ON B.CIFID = C.REFERENCEID AND C.RN = 1
  WHERE
    A.RECSTATUS = 'AA'
