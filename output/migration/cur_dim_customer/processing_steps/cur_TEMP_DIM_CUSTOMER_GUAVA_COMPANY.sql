    TRIM(COALESCE(COUNTRY_CODE_CCRIS, '')) <> '' AND ETL_DT = '${batch_date}'
) AS T4 /* None */
  ON T2.CORRESPONDENCE_COUNTRY = T4.COUNTRY_NAME AND T4.ROW_NUM = 1
