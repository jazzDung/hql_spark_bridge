  SELECT
    ROW_NUMBER() OVER (PARTITION BY COUNTRY_NAME ORDER BY COUNTRY_CODE_CCRIS DESC) AS ROW_NUM,
    COUNTRY_NAME,
    COUNTRY_CODE_CCRIS
  FROM ${cur_schema}.REF_COUNTRY
