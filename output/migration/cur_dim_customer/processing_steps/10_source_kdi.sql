  T1.sst_registration_number AS SST_REGISTRATION_NO, /* None */
  T1.COMPANY_PLACE_BUSINESS AS CUSTOMER_COMPANY_COUNTRY_OF_BUSINESS, /* 20251024 */ /* ,NULL AS CUSTOMER_COMPANY_COUNTRY_OF_BUSINESS */
