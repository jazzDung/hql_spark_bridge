SELECT
  T1.OWNER_ID,
  T1.CONTACT_OWNER_TYPE,
  T1.CONTACT_TYPE,
  T1.CONTACT_VALUE,
  T1.CONTACT_NAME,
  COALESCE(T2.CONTACT_CREATE_DATE, '${batch_timestamp}') AS CONTACT_CREATE_DATE, /* NONE */
  T1.CONTACT_UPDATE_DATE,
  T1.LINE_OF_BUSINESS,
  T1.SOURCE_NAME,
  T1.SOURCE_RECORD_ID,
  T1.SEQUENCE_NO
