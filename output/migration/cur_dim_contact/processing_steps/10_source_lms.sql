  AND T1.CONTACT_TYPE = T2.CONTACT_TYPE
  AND T1.SOURCE_RECORD_ID = T2.SOURCE_RECORD_ID
  AND T1.SEQUENCE_NO = T2.SEQUENCE_NO
WHERE
  T1.RN = 1;

