/* ==============[Group.13a - GUAVA COMPANY - CONTACT TYPE]============== */
INSERT INTO ${cur_schema}.TEMP_DIM_ACCOUNT_CONTACT_GUAVA (
  OWNER_ID, /* None */
  CONTACT_OWNER_TYPE, /* None */
  CONTACT_TYPE, /* None */
  CONTACT_VALUE, /* None */
  CONTACT_NAME, /* None */
  CONTACT_CREATE_DATE, /* None */
  CONTACT_UPDATE_DATE, /* None */
  LINE_OF_BUSINESS, /* None */
  SOURCE_NAME, /* None */
  SOURCE_RECORD_ID, /* None */
  SEQUENCE_NO, /* None */
  PRIORITY /* None */
)
SELECT
  'GUAVA_' || T1.ATTACHMENT_TRANSACTION_INFO AS OWNER_ID, /* None */
  'ACCOUNT' AS CONTACT_OWNER_TYPE, /* None */
  T2.CONTACT_TYPE AS CONTACT_TYPE, /* None */
  T2.EXTERNALCONTACT_PHONENUMBER AS CONTACT_VALUE, /* None */
  T2.EXTERNALCONTACT_NAME AS CONTACT_NAME, /* None */
  T1.ATTACHMENT_OWNER_DATE_CREATION AS CONTACT_CREATE_DATE, /* None */
  NULL AS CONTACT_UPDATE_DATE, /* None */
  'TR' AS LINE_OF_BUSINESS, /* None */
  'GUAVA' AS SOURCE_NAME, /* None */
  T1.ATTACHMENT_TRANSACTION_INFO AS SOURCE_RECORD_ID, /* None */
  T2.SEQUENCE_NO AS SEQUENCE_NO, /* None */
  2 AS PRIORITY /* None */
FROM ${com_schema}.T_GUAVA_COMPANY AS T1 /* None */
INNER JOIN (
  SELECT
    EP.BRANCH_NAME,
    EP.EXTERNALCONTACT_NAME,
    EP.EXTERNALCONTACT_PHONENUMBER,
    EP.CONTACT_TYPE,
    ROW_NUMBER() OVER (PARTITION BY EP.BRANCH_NAME, EP.CONTACT_TYPE ORDER BY EP.EXTERNALCONTACT_PHONENUMBER DESC) AS SEQUENCE_NO
  FROM (
    SELECT
      R.BRANCH_NAME,
      R.EXTERNALCONTACT_NAME,
      R.EXTERNALCONTACT_PHONENUMBER,
      (
        CASE
          WHEN R.EXTERNALCONTACT_PHONENUMBER LIKE '601%'
          THEN 'MOBILE'
          WHEN R.EXTERNALCONTACT_PHONENUMBER LIKE '01%'
          THEN 'MOBILE'
          ELSE 'OFFICE'
        END
      ) AS CONTACT_TYPE
    FROM ${com_schema}.T_GUAVA_BRANCH_CONTACT AS R
    WHERE
      R.ETL_DT = '${batch_date}'
      AND TRIM(COALESCE(R.EXTERNALCONTACT_PHONENUMBER, '')) <> ''
      AND NOT R.EXTERNALCONTACT_PHONENUMBER LIKE '@[%]'
  ) AS EP
  WHERE
    1 = 1
) AS T2 /* None */
  ON T1.BRANCH_NAME = T2.BRANCH_NAME
WHERE
  T1.ETL_DT = '${batch_date}' AND T1.IC_SERIAL_NUMBER = 1;

